package com.zhou.musiccache;

import com.zhou.musiccache.cache.RangeCache;

import org.json.JSONArray;
import org.json.JSONObject;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.Map;

/** 仅调试构建：用 1 KiB 配额和自产字节验证真实磁盘淘汰，不读取账号或歌曲缓存。 */
final class CacheCapacityProbe {
    private static final long BUDGET = 1024;
    private static final String MIME = "audio/wav";
    private static final String OLD = "http://127.0.0.1:8765/media/capacity-old.wav?variant=one";
    private static final String ALIAS = "http://127.0.0.1:8765/media/capacity-old.wav?variant=two";
    private static final String RECENT = "http://127.0.0.1:8765/media/capacity-recent.wav";
    private static final String NEW = "http://127.0.0.1:8765/media/capacity-new.wav";
    private static final Map<String, String> HEADERS = Map.of(
            "Cache-Control", "max-age=3600", "ETag", "\"capacity-generated-v1\"");

    private CacheCapacityProbe() { }

    static void run(File filesDirectory, String run) {
        if (!BuildConfig.DEBUG || run == null || !run.matches("[A-Za-z0-9_-]{1,64}")) return;
        JSONArray checks = new JSONArray();
        JSONArray failed = new JSONArray();
        File runDirectory = new File(filesDirectory, "selftest/" + run);
        File probeDirectory = new File(runDirectory, "capacity");
        long started = System.currentTimeMillis();
        try {
            // 每轮必须新目录，不能借用上次探针文件冒充本次构建的设备结果。
            if (probeDirectory.exists() || !probeDirectory.mkdirs())
                throw new IOException("Capacity probe needs a new run directory");
            exercise(probeDirectory, checks, failed);
        } catch (Exception error) {
            try {
                check(checks, failed, "probe_exception", false,
                        error.getClass().getSimpleName() + ": " + error.getMessage());
            } catch (Exception ignored) { failed.put("probe_exception"); }
        }
        try {
            JSONObject report = new JSONObject().put("passed", failed.length() == 0)
                    .put("checks", checks).put("failed", failed).put("checkCount", checks.length())
                    .put("run", run).put("pid", android.os.Process.myPid())
                    .put("appVersion", BuildConfig.VERSION_NAME).put("budgetBytes", BUDGET)
                    .put("generatedOnly", true).put("elapsedMillis", System.currentTimeMillis() - started);
            try (FileOutputStream output = new FileOutputStream(new File(runDirectory, "capacity.json"))) {
                output.write(report.toString(2).getBytes(StandardCharsets.UTF_8));
                output.getFD().sync();
            }
        } catch (Exception ignored) {
            // 报告缺失由设备验收判失败；探针故障不能令原有网页自测或正常登录进程崩溃。
        }
    }

    private static void exercise(File root, JSONArray checks, JSONArray failed) throws Exception {
        File eviction = new File(root, "eviction");
        RangeCache cache = new RangeCache(eviction, BUDGET, BUDGET);
        byte[] oldBytes = generated(512, 1);
        byte[] recentBytes = generated(512, 2);
        byte[] newBytes = generated(512, 3);
        boolean seeded = put(cache, OLD, oldBytes.length, 0, oldBytes)
                && put(cache, RECENT, recentBytes.length, 0, recentBytes);
        check(checks, failed, "fill_small_budget", seeded && cache.sizeBytes() == BUDGET
                && cache.entries().size() == 2, "Two generated responses fill the 1024-byte budget");
        boolean alias = cache.reuseValidated(ALIAS, RangeCache.resourceKeyForUrl(OLD, true),
                MIME, oldBytes.length, HEADERS);
        check(checks, failed, "establish_old_alias", alias && cache.isAlias(ALIAS)
                && Arrays.equals(read(cache, ALIAS), oldBytes), "Alias initially reads the old generated bytes");

        // 人工设定明确先后，避免同毫秒保存时设备文件系统时间精度影响测试结论。
        long now = System.currentTimeMillis();
        if (!metadata(eviction, OLD).setLastModified(now - 120000)
                || !metadata(eviction, RECENT).setLastModified(now - 60000))
            throw new IOException("Cannot establish deterministic metadata ages");
        check(checks, failed, "admit_new_when_full", put(cache, NEW, newBytes.length, 0, newBytes),
                "A full budget still accepts a new generated response");
        check(checks, failed, "evict_oldest_resource", read(cache, OLD) == null
                && !metadata(eviction, OLD).exists(), "The oldest saved resource is removed");
        check(checks, failed, "preserve_recent_resource", Arrays.equals(read(cache, RECENT), recentBytes),
                "The more recently saved response retains its original bytes");
        check(checks, failed, "remove_evicted_alias", !cache.isAlias(ALIAS) && read(cache, ALIAS) == null
                && !new File(eviction, RangeCache.keyForUrl(ALIAS) + ".alias").exists(),
                "Eviction removes both the alias map entry and its disk metadata");
        check(checks, failed, "read_new_resource", Arrays.equals(read(cache, NEW), newBytes),
                "The newly admitted response reads back byte for byte");
        check(checks, failed, "disk_audio_stays_bounded", cache.sizeBytes() == BUDGET
                && audioBytes(eviction) == BUDGET && !hasTemporary(eviction),
                "Published audio uses 1024 bytes and completed writes leave no temporary files");

        RangeCache restarted = new RangeCache(eviction, BUDGET, BUDGET);
        check(checks, failed, "reload_after_eviction", restarted.entries().size() == 2
                && restarted.sizeBytes() == BUDGET && read(restarted, OLD) == null
                && !restarted.isAlias(ALIAS) && read(restarted, ALIAS) == null
                && Arrays.equals(read(restarted, RECENT), recentBytes)
                && Arrays.equals(read(restarted, NEW), newBytes),
                "Reloading persisted metadata preserves only the two surviving resources");

        File appendDirectory = new File(root, "append");
        RangeCache appendCache = new RangeCache(appendDirectory, BUDGET, BUDGET);
        byte[] complete = generated(768, 4);
        boolean appendSeeded = put(appendCache, OLD, complete.length, 0, Arrays.copyOf(complete, 256))
                && put(appendCache, RECENT, recentBytes.length, 0, recentBytes);
        if (!metadata(appendDirectory, OLD).setLastModified(now - 120000)
                || !metadata(appendDirectory, RECENT).setLastModified(now - 60000))
            throw new IOException("Cannot establish deterministic append metadata ages");
        boolean appended = put(appendCache, OLD, complete.length, 256, Arrays.copyOfRange(complete, 256, 768));
        check(checks, failed, "protect_current_append", appendSeeded && appended
                && Arrays.equals(read(appendCache, OLD), complete) && read(appendCache, RECENT) == null
                && appendCache.sizeBytes() == complete.length && audioBytes(appendDirectory) <= BUDGET,
                "Appending protects its older existing resource and evicts another response");

        File reservationDirectory = new File(root, "reservation");
        RangeCache reservations = new RangeCache(reservationDirectory, BUDGET, BUDGET);
        boolean respectsReservation;
        RangeCache.WriteSession first = reservations.begin(OLD, MIME, 768, 0, 768, HEADERS);
        try {
            RangeCache.WriteSession second = reservations.begin(NEW, MIME, 512, 0, 512, HEADERS);
            respectsReservation = first != null && second == null;
            if (second != null) second.close();
        } finally {
            if (first != null) first.close();
        }
        check(checks, failed, "pending_writes_reserve_budget", respectsReservation,
                "An unfinished 768-byte write prevents reserving another 512 bytes");
        byte[] fullBudget = generated((int) BUDGET, 5);
        check(checks, failed, "cancel_releases_reservation", put(reservations, NEW, BUDGET, 0, fullBudget)
                && Arrays.equals(read(reservations, NEW), fullBudget)
                && reservations.sizeBytes() == BUDGET && audioBytes(reservationDirectory) == BUDGET
                && !hasTemporary(reservationDirectory),
                "Cancelled writes release all reserved capacity for a subsequent full-budget response");

        File cancelledDirectory = new File(root, "cancelled-full");
        RangeCache cancelled = new RangeCache(cancelledDirectory, BUDGET, BUDGET);
        boolean original = put(cancelled, OLD, 512, 0, oldBytes) && put(cancelled, RECENT, 512, 0, recentBytes);
        check(checks, failed, "cancel_at_full_setup", original, "Two generated responses fill committed capacity");
        try (RangeCache.WriteSession partial = cancelled.begin(NEW, MIME, 512, 0, 512, HEADERS)) {
            if (partial == null) throw new IOException("Cannot stage generated response");
            partial.append(newBytes, 0, 128);
            check(checks, failed, "partial_retains_old_audio", cancelled.sizeBytes() == BUDGET
                    && Arrays.equals(read(cancelled, OLD), oldBytes) && Arrays.equals(read(cancelled, RECENT), recentBytes),
                    "Downloading at full capacity leaves both previous responses readable");
            check(checks, failed, "truncated_response_rejected", !partial.finish(), "Only 128 of 512 promised bytes arrived");
        }
        RangeCache afterCancel = new RangeCache(cancelledDirectory, BUDGET, BUDGET);
        check(checks, failed, "cancel_at_full_survives_restart", afterCancel.sizeBytes() == BUDGET
                && Arrays.equals(read(afterCancel, OLD), oldBytes) && Arrays.equals(read(afterCancel, RECENT), recentBytes)
                && !hasTemporary(cancelledDirectory), "Cancelled replacement leaves committed bytes intact across restart");
    }

    private static boolean put(RangeCache cache, String url, long total, long start, byte[] bytes) throws IOException {
        RangeCache.WriteSession session = cache.begin(url, MIME, total, start, bytes.length,
                HEADERS, RangeCache.resourceKeyForUrl(url, true));
        if (session == null) return false;
        try (RangeCache.WriteSession target = session) {
            target.append(bytes, 0, bytes.length);
            return target.finish();
        }
    }

    private static byte[] read(RangeCache cache, String url) throws IOException {
        try (RangeCache.CachedResponse response = cache.open(url, null, RangeCache.resourceKeyForUrl(url, true))) {
            if (response == null) return null;
            ByteArrayOutputStream result = new ByteArrayOutputStream();
            byte[] buffer = new byte[256];
            int count;
            while ((count = response.body.read(buffer)) != -1) result.write(buffer, 0, count);
            return result.toByteArray();
        }
    }

    private static byte[] generated(int length, int seed) {
        byte[] bytes = new byte[length];
        for (int i = 0; i < length; i++) bytes[i] = (byte) (seed * 31 + i * 17);
        return bytes;
    }

    private static File metadata(File directory, String url) {
        return new File(directory, RangeCache.keyForUrl(url) + ".meta");
    }

    private static long audioBytes(File directory) throws IOException {
        File[] files = directory.listFiles();
        if (files == null) throw new IOException("Cannot list generated probe files");
        long bytes = 0;
        for (File file : files) if (file.getName().endsWith(".bin")) bytes += file.length();
        return bytes;
    }

    private static boolean hasTemporary(File directory) throws IOException {
        File[] files = directory.listFiles();
        if (files == null) throw new IOException("Cannot list generated probe files");
        for (File file : files) if (file.getName().endsWith(".part")) return true;
        return false;
    }

    private static void check(JSONArray checks, JSONArray failed, String id, boolean passed, String detail) throws Exception {
        checks.put(new JSONObject().put("id", id).put("ok", passed).put("detail", detail));
        if (!passed) failed.put(id);
    }
}
